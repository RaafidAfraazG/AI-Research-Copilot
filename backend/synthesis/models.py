"""
Strongly typed schemas and data models for Grounded Research Synthesis.
"""
from __future__ import annotations

from enum import Enum
from typing import Any
from pydantic import BaseModel, Field


class SupportStatus(str, Enum):
    """Deterministic support status for factual claims."""
    SUPPORTED = "SUPPORTED"
    PARTIALLY_SUPPORTED = "PARTIALLY_SUPPORTED"
    UNSUPPORTED = "UNSUPPORTED"


class ClaimItem(BaseModel):
    """
    A single factual assertion generated by the LLM, traceable to evidence passages.
    """
    claim_id: str = Field(..., description="Unique claim identifier (e.g. 'claim_001')")
    text: str = Field(..., description="Factual assertion text")
    evidence_ids: list[str] = Field(
        default_factory=list,
        description="References to supporting evidence passage IDs (e.g. ['evidence_001'])",
    )
    citation_ids: list[str] = Field(
        default_factory=list,
        description="Rendered citation identifiers (e.g. ['cite_1', 'cite_2'])",
    )
    support_status: SupportStatus = Field(
        default=SupportStatus.SUPPORTED,
        description="Verified evidence grounding status",
    )


class Citation(BaseModel):
    """
    A verified, human-readable bibliographic citation mapped from evidence passages.
    """
    citation_id: str = Field(..., description="Unique citation identifier (e.g. 'cite_1')")
    number: int = Field(..., description="1-indexed citation number for in-text reference")
    title: str = Field(..., description="Source paper or document title")
    source_type: str = Field(..., description="Source origin (e.g. 'arxiv', 'semantic_scholar', 'web')")
    source_id: str = Field(..., description="Native source ID (e.g. arXiv ID, DOI, URL)")
    authors: list[str] = Field(default_factory=list, description="Author list")
    publication_date: str | None = Field(default=None, description="Publication date if available")
    url: str | None = Field(default=None, description="Canonical source URL")
    doi: str | None = Field(default=None, description="Digital Object Identifier if available")
    arxiv_id: str | None = Field(default=None, description="arXiv ID if available")
    evidence_id: str = Field(..., description="Referenced evidence ID in the prompt")
    formatted_citation: str = Field(..., description="Human-readable citation string")


class SourceProvenance(BaseModel):
    """Aggregated source document metadata."""
    source_id: str
    source_type: str
    title: str
    url: str | None = None
    evidence_count: int = 1


class CitationVerificationResult(BaseModel):
    """
    Audit result produced by the CitationVerifier assessing claim grounding.
    """
    valid: bool = Field(..., description="True if all claims are grounded with no orphan citations")
    errors: list[str] = Field(default_factory=list, description="Grounding errors (e.g. hallucinated evidence IDs)")
    warnings: list[str] = Field(default_factory=list, description="Non-fatal warnings (e.g. orphan citations)")
    unsupported_claim_ids: list[str] = Field(default_factory=list, description="List of claim IDs lacking evidence")
    verified_claim_count: int = Field(default=0, description="Number of fully supported claims")
    total_claim_count: int = Field(default=0, description="Total number of claims evaluated")
    grounding_rate: float = Field(default=0.0, description="Ratio of supported claims to total claims")
    verification_method: str = Field(
        default="structural_evidence_id_check",
        description=(
            "How support was determined. 'structural_evidence_id_check' means a claim is SUPPORTED "
            "when every evidence id it cites exists in the retrieved evidence set."
        ),
    )
    semantic_entailment_checked: bool = Field(
        default=False,
        description=(
            "False: no check that the cited passage actually entails the claim was performed. "
            "SUPPORTED therefore means 'cites retrieved evidence', not 'proven by the passage'."
        ),
    )


class AnswerEvidence(BaseModel):
    """
    An evidence passage that was supplied to the LLM, exposed so clients can inspect
    the text behind a citation. `evidence_id` matches ClaimItem.evidence_ids and
    Citation.evidence_id. Scores are reranker/ranking scores, not probabilities.
    """
    evidence_id: str
    passage_id: str
    document_id: str
    title: str = ""
    source_type: str
    source_id: str
    url: str | None = None
    text: str
    relevance_score: float
    rank: int
    chunk_index: int = 0
    authors: list[str] = Field(default_factory=list)
    publication_date: str | None = None


class ResearchAnswerSection(BaseModel):
    """Thematic section of the research answer."""
    title: str = Field(..., description="Section title")
    claims: list[ClaimItem] = Field(default_factory=list, description="Claims in this section")


class SynthesisMetadata(BaseModel):
    """Operational telemetry and token usage for the synthesis execution."""
    provider: str
    model: str
    planning_latency_ms: float = 0.0
    retrieval_latency_ms: float = 0.0
    generation_latency_ms: float = 0.0
    verification_latency_ms: float = 0.0
    total_latency_ms: float = 0.0
    input_tokens: int | None = None
    output_tokens: int | None = None
    total_tokens: int | None = None
    claim_count: int = 0
    supported_claim_count: int = 0
    partially_supported_claim_count: int = 0
    unsupported_claim_count: int = 0
    query_analysis: dict[str, Any] | None = None
    research_plan: dict[str, Any] | None = None
    retrieval: dict[str, Any] | None = None


class ResearchAnswer(BaseModel):
    """
    Complete, verified, and grounded research answer payload.
    """
    question: str = Field(..., description="Original user research question")
    summary: str = Field(..., description="Executive summary synthesized from evidence")
    sections: list[ResearchAnswerSection] = Field(default_factory=list, description="Structured answer sections")
    claims: list[ClaimItem] = Field(default_factory=list, description="All verified claims")
    citations: list[Citation] = Field(default_factory=list, description="Full bibliographic citations")
    sources: list[SourceProvenance] = Field(default_factory=list, description="Distinct source documents cited")
    evidence: list[AnswerEvidence] = Field(
        default_factory=list,
        description="All evidence passages supplied to the LLM, in backend rank order",
    )
    limitations: list[str] = Field(default_factory=list, description="Known uncertainties or evidence boundaries")
    verification: CitationVerificationResult = Field(..., description="Verification audit results")
    metadata: SynthesisMetadata = Field(..., description="Telemetry and timing metrics")
    insufficient_evidence: bool = Field(default=False, description="True if evidence was inadequate to answer")
    query_analysis: dict[str, Any] | None = Field(default=None, description="Query intelligence and intent analysis")
    research_plan: dict[str, Any] | None = Field(default=None, description="Research decomposition plan")

